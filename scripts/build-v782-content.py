def vocab(level, raw):
    res=[]
    for line in raw.strip().splitlines():
        jp,reading,mm,example,example_my=line.split('|')
        res.append(dict(id=f'{level}-v-{len(res)+1}',word=jp,reading=reading,meaning=mm,example=example,exampleMy=example_my))
    return res

def grammar(level,raw):
    res=[]
    for line in raw.strip().splitlines():
        title,meaning,example,example_my,note=line.split('|')
        res.append(dict(id=f'{level}-g-{len(res)+1}',title=title,meaning=meaning,example=example,exampleMy=example_my,note=note))
    return res

def kanji(level,raw):
    res=[]
    for line in raw.strip().splitlines():
        ch,reading,mm,ex1,ex2=line.split('|')
        res.append(dict(id=f'{level}-k-{len(res)+1}',character=ch,reading=reading,meaning=mm,words=[ex1,ex2]))
    return res

def texts(level, raw):
    res=[]
    for line in raw.strip().splitlines():
        title,passage,question,answers,correct,explanation=line.split('|')
        options=answers.split(' / ')
        assert len(options)==4,(level,title)
        res.append(dict(id=f'{level}-r-{len(res)+1}',title=title,passage=passage,question=question,options=options,answer=int(correct),explanation=explanation))
    return res

def audios(level,raw):
    res=[]
    for line in raw.strip().splitlines():
        title,script,question,answers,correct,explanation=line.split('|')
        options=answers.split(' / ')
        assert len(options)==4,(level,title)
        res.append(dict(id=f'{level}-l-{len(res)+1}',title=title,script=script,question=question,options=options,answer=int(correct),explanation=explanation))
    return res

