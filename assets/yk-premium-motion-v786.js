/** STUDYING WITH YE KUN v7.86.0 — decorative motion only.
 * No dependencies, tracking, external media, timers, backend requests or persistent state.
 * Preserves original anime student/teacher assets and existing learning/scoring logic.
 */
(()=>{
  'use strict';
  if (!document.body || !window.matchMedia) return;
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)');
  if (reduced.matches) return;
  document.body.classList.add('yk86-motion');
  const targets = [...document.querySelectorAll(
    '.study-track, .yk821-hub-welcome, .yk821-hero, .vc-card, .vc-material, .vc-contact'
  )].filter(el => !el.closest('[hidden]'));
  if ('IntersectionObserver' in window) {
    const observer=new IntersectionObserver(entries=>{
      for(const entry of entries){
        if(!entry.isIntersecting)continue;
        entry.target.classList.add('yk86-inview');
        observer.unobserve(entry.target); // every reveal plays only once
      }
    },{threshold:0.08,rootMargin:'0px 0px -18px 0px'});
    targets.forEach((el,index)=>{
      if(el.classList.contains('study-track')||el.classList.contains('vc-card')){
        el.style.setProperty('--yk86-delay',`${(index%3)*55}ms`);
      }
      el.setAttribute('data-yk86-reveal','');
      observer.observe(el);
    });
  } else {
    targets.forEach(el=>el.classList.add('yk86-inview'));
  }
  // Re-run visible video cards only on a real category filter selection.
  // Do not affect filter selection, YouTube iframe or payment/access state.
  if(document.querySelector('.vc-filters')){
    document.querySelectorAll('.vc-filter[data-filter]').forEach(button=>{
      button.addEventListener('click',()=>{
        requestAnimationFrame(()=>{
          document.querySelectorAll('.vc-card:not([hidden])').forEach(el=>{
            el.classList.remove('yk86-filter-in');
            void el.offsetWidth;
            el.classList.add('yk86-filter-in');
          });
        });
      });
    });
  }
  // Existing JLPT feedback is already generated by v7.82.1 using saved
  // verified practice data. Animate the same status component, never infer scores.
  const feedback=document.getElementById('yk821Reaction');
  if(feedback && 'MutationObserver' in window){
    const anim=()=>{
      if(feedback.hidden){feedback.classList.remove('yk86-feedback-show');return;}
      feedback.classList.remove('yk86-feedback-show');
      void feedback.offsetWidth;
      feedback.classList.add('yk86-feedback-show');
    };
    new MutationObserver(anim).observe(feedback,{attributes:true,attributeFilter:['hidden','data-kind']});
  }
  const tip=document.getElementById('yk821TeacherTip');
  const tipCard=tip?.closest('.yk821-lesson-companion');
  if(tipCard && 'MutationObserver' in window){
    new MutationObserver(()=>{
      tipCard.classList.remove('yk86-tip-fresh');
      void tipCard.offsetWidth;
      tipCard.classList.add('yk86-tip-fresh');
    }).observe(tip,{characterData:true,childList:true,subtree:true});
  }
})();
